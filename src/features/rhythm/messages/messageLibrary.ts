export const rhythmMessageLibrary: RhythmMessageTemplate[] = Object.entries(seeds).flatMap(([category, items]) =>
  items.map(([title, text], index) => ({ id: `${category}-${index + 1}`, category: category as RhythmMessageCategory, title, text, ...presentation[category as RhythmMessageCategory] })),
);

export function getRhythmMessages(category: RhythmMessageCategory) {
  return rhythmMessageLibrary.filter((item) => item.category === category);
}

